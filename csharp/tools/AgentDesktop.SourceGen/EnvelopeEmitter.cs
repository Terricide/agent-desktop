using System.Collections.Generic;
using System.Text;

namespace AgentDesktop.SourceGen;

/// <summary>Writes the source for one captured type: each field appended at its declared
/// position, with no runtime type model consulted.</summary>
internal static class EnvelopeEmitter
{
    internal static string Snake(string name)
    {
        var builder = new StringBuilder();
        for (var index = 0; index < name.Length; index++)
        {
            var character = name[index];
            if (char.IsUpper(character)
                && index > 0
                && (char.IsLower(name[index - 1]) || index + 1 < name.Length && char.IsLower(name[index + 1])))
            {
                builder.Append('_');
            }

            builder.Append(char.ToLowerInvariant(character));
        }

        return builder.ToString();
    }

    internal static string Generate(Model model)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using AgentDesktop.Core.Response;");
        builder.AppendLine();
        if (model.Namespace.Length > 0)
        {
            builder.AppendLine($"namespace {model.Namespace};");
            builder.AppendLine();
        }

        builder.AppendLine($"partial {model.Keyword} {model.Name}");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>Writes this type's fields inside the object the caller has opened.</summary>");
        builder.AppendLine("    public void WriteFields(EnvelopeWriter w)");
        builder.AppendLine("    {");
        foreach (var field in model.Fields)
        {
            builder.Append(Statement(field));
        }

        builder.AppendLine("    }");
        builder.AppendLine("    public void WriteJson(EnvelopeWriter w)");
        builder.AppendLine("    {");
        builder.AppendLine("        w.ObjectStart();");
        builder.AppendLine("        WriteFields(w);");
        builder.AppendLine("        w.ObjectEnd();");
        builder.AppendLine("    }");
        foreach (var field in model.Fields)
        {
            if (field.Kind == Kind.Enum)
            {
                builder.Append(EnumMapper(field));
            }
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string Statement(Field field)
    {
        var builder = new StringBuilder();
        if (field.Mode == Mode.Flatten)
        {
            builder.AppendLine($"        {field.Property}.WriteFields(w);");
            return builder.ToString();
        }

        if (field.Kind == Kind.ListString || field.Kind == Kind.ListNested)
        {
            var item = field.Kind == Kind.ListString ? "w.String(item);" : "item.WriteJson(w);";
            builder.AppendLine($"        if ({field.Property}.Count > 0)");
            builder.AppendLine("        {");
            builder.AppendLine($"            w.Key(\"{field.Json}\");");
            builder.AppendLine("            w.ArrayStart();");
            builder.AppendLine($"            foreach (var item in {field.Property})");
            builder.AppendLine("            {");
            builder.AppendLine("                w.Member();");
            builder.AppendLine($"                {item}");
            builder.AppendLine("            }");
            builder.AppendLine("            w.ArrayEnd();");
            builder.AppendLine("        }");
            return builder.ToString();
        }

        if (field.Mode == Mode.SkipWhenFalse)
        {
            builder.AppendLine($"        if ({field.Property})");
            builder.AppendLine("        {");
            builder.AppendLine($"            w.Key(\"{field.Json}\");");
            builder.AppendLine("            w.Bool(true);");
            builder.AppendLine("        }");
            return builder.ToString();
        }

        var value = field.Kind switch
        {
            Kind.String => $"w.String({field.Property});",
            Kind.Bool => $"w.Bool({field.Property});",
            Kind.Number => $"w.Number((long){field.Property});",
            Kind.Double => $"w.Number((double){field.Property});",
            Kind.Raw => $"w.Raw({field.Property}.ToJsonString());",
            Kind.Nested => field.ValueNullable ? $"{field.Property}.Value.WriteJson(w);" : $"{field.Property}.WriteJson(w);",
            Kind.Enum => $"w.String({field.Mapper}({field.Property}));",
            _ => string.Empty,
        };

        if (field.Mode == Mode.RawJson)
        {
            builder.AppendLine($"        if ({field.Property} is not null)");
            builder.AppendLine("        {");
            builder.AppendLine($"            w.Key(\"{field.Json}\");");
            builder.AppendLine($"            w.Raw({field.Property}.ToJsonString());");
            builder.AppendLine("        }");
            return builder.ToString();
        }

        if (field.Mode == Mode.RawText)
        {
            builder.AppendLine($"        if ({field.Property} is not null)");
            builder.AppendLine("        {");
            builder.AppendLine($"            w.Key(\"{field.Json}\");");
            builder.AppendLine($"            w.Raw({field.Property});");
            builder.AppendLine("        }");
            return builder.ToString();
        }

        if (field.Nullable)
        {
            builder.AppendLine($"        if ({field.Property} is not null)");
            builder.AppendLine("        {");
            builder.AppendLine($"            w.Key(\"{field.Json}\");");
            builder.AppendLine($"            {value}");
            builder.AppendLine("        }");
            return builder.ToString();
        }

        builder.AppendLine($"        w.Key(\"{field.Json}\");");
        builder.AppendLine($"        {value}");
        return builder.ToString();
    }

    private static string EnumMapper(Field field)
    {
        var builder = new StringBuilder();
        builder.AppendLine();
        builder.AppendLine($"    private static string {field.Mapper}({field.Display} value) => value switch");
        builder.AppendLine("    {");
        foreach (var member in field.EnumMembers)
        {
            builder.AppendLine($"        {field.Display}.{member} => \"{Snake(member)}\",");
        }

        builder.AppendLine("        _ => string.Empty,");
        builder.AppendLine("    };");
        return builder.ToString();
    }

}

internal sealed class Model(string namespaceName, string name, string keyword)
    {
        public bool IsEmpty { get; set; }

        public List<Field> Fields { get; } = new();

        public string FileName => (namespaceName.Length > 0 ? namespaceName + "." : string.Empty) + name + ".Envelope.g.cs";

        public string Source => EnvelopeEmitter.Generate(this);

        public string Namespace => namespaceName;

        public string Name => name;

        public string Keyword => keyword;
    }

internal sealed class Field(string property, string json, Mode mode, Kind kind, bool nullable, bool valueNullable, string display)
    {
        public string Property => property;

        public string Json => json;

        public Mode Mode => mode;

        public Kind Kind => kind;

        public bool Nullable => nullable;

        public bool ValueNullable => valueNullable;

        public string Display => display;

        public List<string> EnumMembers { get; set; } = new();

        public string Mapper => "EnvelopeNameFor" + property;
    }

internal enum Kind
    {
        String,
        Bool,
        Number,
        Double,
        Raw,
        Nested,
        ListString,
        ListNested,
        Enum,
        Unsupported,
    }

internal enum Mode
    {
        Standard,
        Flatten,
        Skip,
        SkipWhenFalse,
        RawJson,
        RawText,
    }

